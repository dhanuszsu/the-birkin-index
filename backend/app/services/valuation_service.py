from sqlalchemy.orm import Session
from fastapi import HTTPException, status
from app.schemas.valuation import ValuationPredictRequest, ValuationPredictResponse
from app.services.model_service import ModelService

class ValuationService:
    @staticmethod
    def predict_valuation(db: Session, request: ValuationPredictRequest) -> ValuationPredictResponse:
        model_status = ModelService.get_model_status(db)
        
        # Strictly enforce integrity rule: Refuse to generate estimates when no validated model is available
        if not model_status.is_available:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail={
                    "error": "VALUATION_MODEL_UNAVAILABLE",
                    "message": (
                        "Valuation prediction is currently unavailable. No validated machine learning model has "
                        "been trained on verified research data. The Birkin Index strictly refrains from outputting "
                        "fabricated prices or heuristic guestimates."
                    ),
                    "status": model_status.status,
                    "reason": model_status.reason,
                    "eligible_records_count": model_status.eligible_for_ml_count,
                    "minimum_records_required": model_status.minimum_records_required,
                }
            )
            
        # When an active validated model is present, execute inference here:
        # (This path will be active once genuine research dataset reaches threshold and train.py exports model)
        return ValuationPredictResponse(
            status="success",
            currency=request.currency or "EUR",
            explanation="Valuation generated by validated regression model."
        )
